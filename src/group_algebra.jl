"""
group_algebra.jl — Two-block group-algebra (2BGA) codes for arbitrary finite groups.

Mirrors `research/kit/group_algebra.py` (Lin & Pryadko, arXiv:2306.16400).

Construction:
  G a finite group, |G|=N. Pick supports a,b ⊆ G.
  L(g) = left-regular permutation:  L(g) e_h = e_{g·h}
  R(g) = right-regular permutation: R(g) e_h = e_{h·g}
  L(a)=Σ_{g∈a}L(g),  R(b)=Σ_{g∈b}R(g)
  H_X=[L(a) | R(b)], H_Z=[R(b)ᵀ | L(a)ᵀ],  n=2N

CSS is automatic: left and right actions commute, so H_X·H_Zᵀ=0 mod 2.

Group encoding:
  Cayley table `mul` is N×N Int matrix, 1-indexed, identity at index 1.
  `mul[i,j]` = index of gᵢ·gⱼ. Built from permutation generators via
  `perm_group` or the helpers (`cyclic_group`, `dihedral_group`, `metacyclic`, …).
  Elements are stored as permutation vectors `Vector{Int}` 1-indexed on 1:degree.

Public:
  - `cyclic_group(n)`, `cyclic_product(orders...)`, `dihedral_group(n)`,
    `metacyclic(n,k,r)`, `sym_group(n)`, `alt_group(n)`, `perm_group(gens, degree)`
  - `perm_matrix(p)`, `left_regular_rep(mul,g)`, `right_regular_rep(mul,g)`
  - `build_2bga(mul, a, b)` / `build_2bga((mul,elems), a, b)` → (Hx,Hz)
"""

using SparseArrays

# ---------------------------------------------------------------------------
# Permutation helpers (1-indexed)
# ---------------------------------------------------------------------------

"""    _compose(p, q) -> Vector{Int}

Permutation composition (p ∘ q)(i) = p[q[i]] — apply q then p.
Both `p`,`q` are `Vector{Int}` 1-indexed on 1:degree."""
function _compose(p::AbstractVector{Int}, q::AbstractVector{Int})::Vector{Int}
    return [p[q[i]] for i in 1:length(q)]
end

"""    perm_matrix(p) -> SparseMatrixCSC{Bool}

Permutation matrix for `p`: M[p[c], c] = 1."""
function perm_matrix(p::AbstractVector{Int})::SparseMatrixCSC{Bool,Int}
    N = length(p)
    return sparse(Vector{Int}(p), collect(1:N), fill(true, N), N, N)
end

# ---------------------------------------------------------------------------
# Group construction — Cayley table mul (N×N, 1-indexed, identity=1)
# ---------------------------------------------------------------------------

"""
    perm_group(gens, degree) -> (mul, elems)

Group generated by permutation `gens` (each `Vector{Int}` 1-indexed on 1:degree)
via BFS closure. Returns `(mul, elems)` where `mul[i,j]` is the index (1-based)
of gᵢ·gⱼ and `elems` is the element list (identity at index 1).
"""
function perm_group(gens::AbstractVector{<:AbstractVector{Int}}, degree::Int)
    isempty(gens) && error("perm_group: need at least one generator")
    ident = collect(1:degree)
    elems = Vector{Vector{Int}}()
    push!(elems, ident)
    index = Dict{Vector{Int},Int}(copy(ident) => 1)
    frontier = Vector{Vector{Int}}([ident])
    while !isempty(frontier)
        nxt = Vector{Vector{Int}}()
        for e in frontier, g in gens
            h = _compose(e, g)
            if !haskey(index, h)
                index[h] = length(elems) + 1
                push!(elems, h)
                push!(nxt, h)
            end
        end
        frontier = nxt
    end
    N = length(elems)
    mul = zeros(Int, N, N)
    for i in 1:N, j in 1:N
        mul[i, j] = index[_compose(elems[i], elems[j])]
    end
    return mul, elems
end

# single-arg vector convenience
perm_group(gens::AbstractVector{<:AbstractVector{Int}}) = perm_group(gens, length(gens[1]))

"""
    cyclic_group(n) -> (mul, elems)

Cyclic group C_n (order n) as a Cayley table. Identity at index 1.
"""
function cyclic_group(n::Int)
    r = vcat(collect(2:n), [1])  # n-cycle
    return perm_group([r], n)
end

"""
    cyclic_product(orders...) -> (mul, elems)

Abelian group Z_{o1} × … × Z_{ok} as a Cayley table. Identity at index 1.
On Z_l × Z_m this reproduces the `bb.jl` torus family.
"""
function cyclic_product(orders::Int...)
    @assert !isempty(orders) "need at least one order"
    tuples = Vector{Vector{Int}}()
    # cartesian product via recursion
    function rec(idx::Int, cur::Vector{Int})
        if idx > length(orders)
            push!(tuples, copy(cur))
            return
        end
        for v in 0:orders[idx]-1
            push!(cur, v)
            rec(idx + 1, cur)
            pop!(cur)
        end
    end
    rec(1, Int[])
    N = length(tuples)
    # map tuple -> index
    tmap = Dict{Vector{Int},Int}()
    for (i, t) in enumerate(tuples)
        tmap[t] = i
    end
    mul = zeros(Int, N, N)
    for i in 1:N, j in 1:N
        s = [(tuples[i][d] + tuples[j][d]) % orders[d] for d in 1:length(orders)]
        mul[i, j] = tmap[s]
    end
    return mul, tuples
end

"""
    direct_product(mulA, mulB) -> (mul, elems)

Cayley table of A × B.
"""
function direct_product(mulA::Matrix{Int}, mulB::Matrix{Int})
    a = size(mulA, 1)
    b = size(mulB, 1)
    N = a * b
    mul = zeros(Int, N, N)
    # index: (i,j) -> (i-1)*b + j  (1-indexed)
    for i in 1:a, j in 1:b, ii in 1:a, jj in 1:b
        mul[(i-1)*b+j, (ii-1)*b+jj] = (mulA[i, ii]-1)*b + mulB[j, jj]
    end
    elems = [(i, j) for i in 1:a for j in 1:b]
    return mul, elems
end

"""
    metacyclic(n, k, r) -> (mul, elems)

Semidirect product C_n ⋊ C_k with action j: i ↦ r^j · i (mod n).
Requires r^k ≡ 1 (mod n). Elements (i,j) at index i*k+j+1; identity (0,0)=1.
Dihedral D_n = metacyclic(n, 2, n-1).
"""
function metacyclic(n::Int, k::Int, r::Int)
    @assert powermod(r, k, n) == 1 "r^k != 1 mod n: $r^$k mod $n = $(powermod(r,k,n))"
    rp = [powermod(r, j, n) for j in 0:k-1]
    idx(i, j) = mod(i, n) * k + mod(j, k) + 1
    N = n * k
    mul = zeros(Int, N, N)
    for i in 0:n-1, j in 0:k-1, ii in 0:n-1, jj in 0:k-1
        mul[idx(i, j), idx(ii, jj)] = idx(i + rp[j+1] * ii, j + jj)
    end
    elems = [(i, j) for i in 0:n-1 for j in 0:k-1]
    return mul, elems
end

"""
    dihedral_group(n) -> (mul, elems)

Dihedral group D_n of order 2n (rotation r, reflection s) on n points.
Presentation ⟨r,s | r^n=s²=1, srs=r⁻¹⟩.
"""
function dihedral_group(n::Int)
    r = vcat(collect(2:n), [1])  # i -> i+1 mod n
    s = Vector{Int}(undef, n)
    # 0-indexed s[i]=(-i) mod n; 1-indexed: s[1]=1, s[2]=n, s[3]=n-1, ...
    for i in 1:n
        s[i] = mod1(1 - (i - 1), n)  # 1-indexed modular
        # check: i=1->1, i=2->n, i=3->n-1 ...
    end
    # verify python mapping: s = (-i) mod n in 0-indexed => s[0]=0 => Julia s[1]=1 good
    return perm_group([r, s], n)
end

"""
    sym_group(n) -> (mul, elems)

Symmetric group S_n (order n!).
"""
function sym_group(n::Int)
    # transposition (0 1) -> Julia (1 2)
    cyc = collect(1:n)
    cyc[1], cyc[2] = 2, 1
    rot = vcat(collect(2:n), [1])
    return perm_group(Vector{Vector{Int}}([cyc, rot]), n)
end

"""
    alt_group(n) -> (mul, elems)

Alternating group A_n (order n!/2).
"""
function alt_group(n::Int)
    three = collect(1:n)
    # (0 1 2) -> Julia (1 2 3) cycle
    three[1], three[2], three[3] = 2, 3, 1
    longc = if isodd(n)
        vcat(collect(2:n), [1])
    else
        # [0] + [1+(i+1)%(n-1) for i in 0..n-2] in 0-indexed
        # 0-indexed longc[0]=0 fixed, rest is shift of 1..n-1
        tmp = collect(1:n)
        tmp[1] = 1
        for i in 2:n
            tmp[i] = 1 + mod(i - 2 + 1, n - 1) + 1  # messy; simpler: build 0-index then convert
        end
        # rebuild correctly via 0-index logic then convert to 1-indexed
        z = zeros(Int, n)
        # 0-indexed: longc[0]=0, longc[i]=1+( (i-1+1) % (n-1)) for i=1..n-1
        for i0 in 0:n-1
            if i0 == 0
                z[i0+1] = 0
            else
                z[i0+1] = 1 + mod((i0 - 1) + 1, n - 1)
            end
        end
        # convert 0-indexed perm z to 1-indexed
        [z[i] + 1 for i in 1:n]
    end
    return perm_group(Vector{Vector{Int}}([three, longc]), n)
end

