"""    left_regular_rep(mul, g) -> SparseMatrixCSC{Bool}

Permutation matrix L(g): L(g)[g·h, h] = 1."""
function left_regular_rep(mul::Matrix{Int}, g::Int)::SparseMatrixCSC{Bool,Int}
    N = size(mul, 1)
    @assert 1 <= g <= N
    p = [mul[g, h] for h in 1:N]
    return perm_matrix(p)
end

"""    right_regular_rep(mul, g) -> SparseMatrixCSC{Bool}

Permutation matrix R(g): R(g)[h·g, h] = 1."""
function right_regular_rep(mul::Matrix{Int}, g::Int)::SparseMatrixCSC{Bool,Int}
    N = size(mul, 1)
    @assert 1 <= g <= N
    p = [mul[h, g] for h in 1:N]
    return perm_matrix(p)
end

# ---------------------------------------------------------------------------
# Block sum helper (mod 2, sparse, toggle semantics)
# ---------------------------------------------------------------------------

function _block_from_perms(perms::Vector{Vector{Int}}, m::Int)::SparseMatrixCSC{Bool,Int}
    # toggle set: (row,col) -> Bool
    pos = Dict{Tuple{Int,Int},Bool}()
    for p in perms
        for c in 1:m
            key = (p[c], c)
            pos[key] = !get(pos, key, false)
        end
    end
    I = Int[]; J = Int[]
    sizehint!(I, length(pos)); sizehint!(J, length(pos))
    for (k, v) in pos
        v || continue
        push!(I, k[1]); push!(J, k[2])
    end
    return sparse(I, J, fill(true, length(I)), m, m)
end

function _block_regular(mul::Matrix{Int}, terms::AbstractVector{Int}, side::Symbol)::SparseMatrixCSC{Bool,Int}
    N = size(mul, 1)
    perms = Vector{Vector{Int}}()
    for g in terms
        @assert 1 <= g <= N "group index $g out of range 1..$N"
        if side === :L
            push!(perms, [mul[g, h] for h in 1:N])
        else
            push!(perms, [mul[h, g] for h in 1:N])
        end
    end
    return _block_from_perms(perms, N)
end

# ---------------------------------------------------------------------------
# Public 2BGA builder
# ---------------------------------------------------------------------------

"""
    build_2bga(mul, a, b) -> (Hx, Hz)

Two-block group-algebra code from Cayley table `mul` (N×N, 1-indexed) with
`a, b` lists of element indices (1-based, identity=1). Returns `Hx, Hz` as
`SparseMatrixCSC{Bool}` of shape (N, 2N). CSS is guaranteed.

Also accepts `build_2bga((mul,elems), a, b)` or `build_2bga(G, a, b)` where
`G` is a `(mul, elems)` tuple from the group builders.

Element indices are 1-based (Julia convention); the Python kit uses 0-based.
Convert by adding 1 when porting Python examples.
"""
function build_2bga(mul::Matrix{Int}, a::AbstractVector{Int}, b::AbstractVector{Int})
    La = _block_regular(mul, collect(Int, a), :L)
    Rb = _block_regular(mul, collect(Int, b), :R)
    Hx = hcat(La, Rb)
    Hz = hcat(transpose(Rb), transpose(La))
    Hx = SparseMatrixCSC{Bool,Int}(sparse(Hx))
    Hz = SparseMatrixCSC{Bool,Int}(sparse(Hz))
    return Hx, Hz
end

# tuple overload
function build_2bga(G::Tuple{Matrix{Int},Any}, a::AbstractVector, b::AbstractVector)
    return build_2bga(G[1], collect(Int, a), collect(Int, b))
end

# vector-of-perms overload: if G is just a vector of perms (unlikely), error helpfully
function build_2bga(G::AbstractVector{<:AbstractVector{Int}}, a::AbstractVector, b::AbstractVector)
    error("build_2bga: pass the Cayley table `mul` (or `(mul,elems)` tuple) from dihedral_group/cyclic_product, not the perm list. Use `G, elems = dihedral_group(n); build_2bga(G, a, b)` with a,b as 1-based element indices.")
end

