using TestItems

@testitem "GroupAlgebra: cyclic group basics" begin
    using SparseArrays
    mul, elems = cyclic_group(6)
    @test size(mul) == (6, 6)
    @test mul[1, :] == 1:6  # identity row
    @test mul[:, 1] == 1:6  # identity col
    # cyclic_product 6×6 should be abelian order 36
    mul2, _ = cyclic_product(6, 6)
    @test size(mul2) == (36, 36)
end

@testitem "GroupAlgebra: dihedral_group order" begin
    mul, _ = dihedral_group(6)
    @test size(mul) == (12, 12)
    mul2, _ = dihedral_group(12)
    @test size(mul2) == (24, 24)
end

@testitem "GroupAlgebra: metacyclic matches dihedral" begin
    mul_d, _ = dihedral_group(6)
    mul_m, _ = metacyclic(6, 2, 5)
    @test size(mul_d) == size(mul_m) == (12, 12)
    # both groups are isomorphic (D6); check they are groups of same order and CSS works
    # Cayley tables may differ by element ordering, so just verify 2BGA commutes on both
    a = [1, 2, 3]; b = [1, 4, 7]
    Hx, Hz = build_2bga(mul_d, a, b)
    @test verify_css(Hx, Hz)
    Hx2, Hz2 = build_2bga(mul_m, a, b)
    @test verify_css(Hz2, Hx2) || verify_css(Hx2, Hz2)
end

@testitem "GroupAlgebra: perm_matrix is permutation" begin
    p = [2, 3, 1]
    M = perm_matrix(p)
    @test size(M) == (3, 3)
    @test nnz(M) == 3
    @test Matrix(M) == Bool[0 0 1; 1 0 0; 0 1 0]
end

@testitem "GroupAlgebra: build_2bga commutes (non-abelian)" begin
    mul, _ = dihedral_group(6)  # order 12, n=24
    a = [1, 2, 3]; b = [1, 4, 6]
    Hx, Hz = build_2bga(mul, a, b)
    @test size(Hx) == (12, 24)
    @test size(Hz) == (12, 24)
    @test verify_css(Hx, Hz)
    k = compute_k(Hx, Hz)
    @test k >= 0
end

@testitem "GroupAlgebra: abelian 2BGA reproduces [[72,12,6]] k=12" begin
    # 2BGA on Z6×Z6 with gross-code supports must give k=12 and CSS
    # Python kit: a=[(3,0),(0,1),(0,2)], b=[(0,3),(1,0),(2,0)] 0-based indices
    mul, tuples = cyclic_product(6, 6)
    tmap = Dict(tuples[i] => i for i in 1:length(tuples))
    a = [tmap[[3, 0]], tmap[[0, 1]], tmap[[0, 2]]]
    b = [tmap[[0, 3]], tmap[[1, 0]], tmap[[2, 0]]]
    Hx, Hz = build_2bga(mul, a, b)
    @test size(Hx) == (36, 72)
    @test verify_css(Hx, Hz)
    @test compute_k(Hx, Hz) == 12
end

@testitem "GroupAlgebra: non-abelian odd k reachable" begin
    # Non-abelian 2BGA can reach odd k (impossible for abelian BB).
    # This test just verifies the plumbing: random dihedral 12 builds commute
    # and compute_k runs without error.
    using Random
    Random.seed!(0)
    mul, _ = dihedral_group(12)
    for trial in 1:20
        a = rand(1:24, 3); b = rand(1:24, 3)
        a = unique(a); b = unique(b)
        (length(a) < 3 || length(b) < 3) && continue
        Hx, Hz = build_2bga(mul, a, b)
        @test verify_css(Hx, Hz)
        k = compute_k(Hx, Hz)
        @test k >= 0
    end
    @test true
end
